void ST7920_DrawChar(char chr)
{
    ST7920_Glyph *glyph = ST7920_FontGlyphs + chr;

    int glyphWidth = ST7920_MONOSPACE ? 8 : ST7920_GetGlyphWidth(glyph);

    if (ST7920_CursorX + glyphWidth > ST7920_WrapX)
    {
        ST7920_CursorX = ST7920_ORIGIN_X;
        ST7920_CursorY += ST7920_LINE_HEIGHT;
    }

    for (int localX = glyph->drawingStartEnd >> 0 & 0b111, i = 0; i < glyphWidth && ST7920_CursorX < ST7920_WrapX; ST7920_CursorX++, localX++, i++)
    {
        u8 column = glyph->cols[localX];

        u8 rightShift = ST7920_CursorX % 8;
        u8 mask       = ~(0x80 >> rightShift);

        for (int y = ST7920_CursorY, j = 7; j >= 0 && y < 64; j--, y++)
        {
            u8  rowIdx = ST7920_CursorX / 8;
            u16 pxIdx  = y * 16 + rowIdx;

            u8 row = ST7920_BackBuf[pxIdx];
            row &= mask;
            u8 bit = column << j & 0x80;
            row |= bit >> rightShift;

            ST7920_BackBuf[pxIdx] = row;
        }
    }
}

void ST7920_DrawStringLen(char *str, u8 length)
{
    for (int i = 0; i < length; ++i)
    {
        char c = *str++;
        if (c == '\n')
        {
            ST7920_CursorY += ST7920_LINE_HEIGHT;
            ST7920_CursorX = ST7920_ORIGIN_X;
            continue;
        }

        ST7920_DrawChar(c);
        ST7920_CursorX += ST7920_FONT_SPACING_X;
    }
}

void ST7920_DrawString(char *str)
{
    ST7920_DrawStringLen(str, strlen(str));
}

void ST7920_DrawStringAtPos(char *str, int x, int y)
{
    ST7920_CursorX = x;
    ST7920_CursorY = y;
    ST7920_DrawString(str);
}

void ST7920_DrawStringAtPosRightJustified(char *str, int x, int y)
{
    ST7920_DrawStringAtPos(str, max(0, x - ST7920_GetStringWidth(str)), y);
}

void ST7920_DrawStringLenCenteredInRect(char *str, u8 length, u8 x, u8 y, u8 width, u8 height, bool vertically, bool horizontally)
{
    // ST7920_DrawRectangle(x, y, width, height, 1);

    if (!vertically && !horizontally)
    {
        // ST7920_SetOrigin(x, y);
        ST7920_CursorY = y;
        ST7920_DrawStringLen(str, length);

        return;
    }

    u8 lineLengths[64 / ST7920_FONT_HEIGHT] = {};

    u8 pixelLenCurrentLine = 0;
    u8 pixelHeight         = 0;
    u8 line                = 0;

    for (int i = 0; i < length; ++i)
    {
        char c = str[i];

        if (c != '\n')
        {
            pixelLenCurrentLine += ST7920_GetGlyphWidth(ST7920_FontGlyphs + c);
        }

        if (c == '\n' || i == length - 1)
        {
            lineLengths[line++] = pixelLenCurrentLine + (length - 1) * ST7920_FONT_SPACING_X;
            pixelLenCurrentLine = 0;
            pixelHeight += ST7920_LINE_HEIGHT;
        }
    }

    // f32 marginY = vertically ? (height - pixelHeight) / 2.0F : 0;
    // f32 cursorY = marginY >= 0 ? y + marginY : y;

    if (line == 1)
    {
        pixelHeight--;
    }

    int marginY = vertically ? ((int) height - pixelHeight) / 2 : 0;
    u8  cursorY = marginY >= 0 ? y + marginY : y;

    ST7920_CursorY = cursorY;

    line        = 0;
    u8 lastLine = 0xFF;

    for (int i = 0; i < length; ++i)
    {
        if (line != lastLine)
        {
            int marginX = horizontally ? ((int) width - lineLengths[line]) / 2 : 0;
            u8  cursorX = marginX >= 0 ? x + marginX : x;

            // ST7920_DrawRectangle(x, ST7920_CursorY, marginX, ST7920_LINE_HEIGHT, 1);

            // ST7920_ORIGIN_X = cursorX;
            ST7920_CursorX = cursorX;
        }
        lastLine = line;

        // ST7920_DrawRectangle(ST7920_ORIGIN_Y, ST7920_CursorY, max(lineLengths[line], 1), ST7920_FONT_HEIGHT, 1);

        char c = *str++;
        if (c == '\n')
        {
            line++;
            ST7920_CursorY += ST7920_LINE_HEIGHT;
            continue;
        }

        ST7920_DrawChar(c);
        ST7920_CursorX += ST7920_FONT_SPACING_X;
    }

    ST7920_CursorX = x;
}

void ST7920_DrawStringCenteredInRect(char *str, u8 x, u8 y, u8 width, u8 height, bool vertically, bool horizontally)
{
    ST7920_DrawStringLenCenteredInRect(str, strlen(str), x, y, width, height, vertically, horizontally);
}

int ST7920_GetGlyphWidth(ST7920_Glyph *g)
{
    u8 drawingStartEnd = g->drawingStartEnd;

    u8 drawingStart = (drawingStartEnd >> 0) & 0b111;
    u8 drawingEnd   = (drawingStartEnd >> 3) & 0b111;

    int glyphWidth = ST7920_MONOSPACE ? 8 : 1 + drawingEnd - drawingStart;

    return glyphWidth;
}

int ST7920_GetStringWidth(char *str)
{
    char *p = str;

    int maxWidth = 0;
    int tmpWidth = 0;

    char c;
    while (c = *p++)
    {
        char next = *p;

        if (c == '\n')
        {
            if (tmpWidth > maxWidth)
            {
                maxWidth = tmpWidth;
            }
            tmpWidth = 0;
            continue;
        }

        ST7920_Glyph *glyph = ST7920_FontGlyphs + c;
        tmpWidth += (ST7920_MONOSPACE ? 8 : ST7920_GetGlyphWidth(glyph)) + (next == 0 ? 0 : ST7920_FONT_SPACING_X);
    }

    return max(maxWidth, tmpWidth);
}

void ST7920_InvertRegion(int x0, int y0, int x1, int y1)
{
    for (int y = y0; y < y1; y++)
    {
        int x1idx = x1 >> 3;
        int x0idx = x0 >> 3;
        int x0rem = x0 & 7;

        int idx = y * 16 + x0idx;

        int remaining = x1 - x0;

        if (remaining < 8)
        {
            int x1rem = x1 & 7;

            // if the line is less than 1 cell long and spans one cell
            if (x0idx == x1idx)
            {
                u8 mask = 0xFF >> x0rem;
                mask ^= (1 << (8 - x1rem)) - 1;

                ST7920_BackBuf[idx] ^= mask;
            }
            else
            {
                u8 mask = 0xFF >> x0rem;
                ST7920_BackBuf[idx++] ^= mask;

                mask = 0xFF << (8 - x1rem);
                ST7920_BackBuf[idx] ^= mask;
            }
            continue;
        }

        // left side remainder
        if (x0rem)
        {
            u8 mask = 0xFF >> x0rem;
            ST7920_BackBuf[idx++] ^= mask;
            remaining -= 8 - x0rem;
        }

        // whole lines
        for (int i = 0; remaining >= 8; ++i, idx++)
        {
            ST7920_BackBuf[idx] ^= 0xFF;
            remaining -= 8;
        }

        // right side remainder
        if (remaining)
        {
            u8 mask = 0xFF << (8 - remaining);

            ST7920_BackBuf[idx] ^= mask;
        }
    }
}

void ST7920_DrawCheckerboard(int x0, int y0, int x1, int y1)
{
    bool flip = ST7920_DottedDefaultState;

    for (int y = y0; y < y1; y++)
    {
        flip = !flip;

        u8 fill = flip ? 0xAA : 0x55;

        int x1idx = x1 >> 3;
        int x0idx = x0 >> 3;
        int x0rem = x0 & 7;
        int x1rem = x1 & 7;

        int idx = y * 16 + x0idx;

        int remaining = x1 - x0;
        if (remaining < 8)
        {
            // if the line is less than 1 cell long and spans one cell
            if (x0idx == x1idx)
            {
                u8 mask = 0xFF >> x0rem;
                mask ^= (1 << (8 - x1rem)) - 1;

                ST7920_BackBuf[idx] |= fill & mask;
            }
            else
            {
                u8 mask = 0xFF >> x0rem;
                ST7920_BackBuf[idx++] |= fill & mask;

                mask = 0xFF << (8 - x1rem);
                ST7920_BackBuf[idx] |= fill & mask;
            }
            continue;
        }

        // left side remainder
        if (x0rem)
        {
            u8 mask = 0xFF >> x0rem;
            ST7920_BackBuf[idx++] |= fill & mask;
            remaining -= 8 - x0rem;
        }

        // whole lines
        for (int i = 0; remaining >= 8; ++i, idx++, remaining -= 8)
        {
            ST7920_BackBuf[idx] |= fill;
        }

        // right side remainder
        if (x1rem)
        {
            u8 mask = 0xFF << (8 - x1rem);

            ST7920_BackBuf[idx] |= fill & mask;
        }
    }
}

void ST7920_DrawLineHorizontalEx(u8 x, u8 y, u8 length, bool dotted)
{
    int remaining = length;

    int x0rem = x & 7;
    int idx   = y * 16 + x / 8;

    if (x0rem)
    {
        int count = 8 - x0rem;

        if (count > length)
        {
            u8 mask = (1 << length) - 1;
            mask <<= count - length;
            ST7920_BackBuf[idx] |= mask;
            return;
        }

        // right justified
        u8 mask = (1 << count) - 1;
        ST7920_BackBuf[idx++] |= mask;

        remaining -= count;
    }

    for (int i = 0; remaining >= 8; ++i, remaining -= 8, idx++)
    {
        ST7920_BackBuf[idx] = 0xFF;
    }

    if (remaining > 0)
    {
        // left justified
        ST7920_BackBuf[idx] |= 0xFF << (8 - remaining);
    }

    if (dotted)
    {
        for (int i = 0, _x = x + !ST7920_DottedDefaultState; i < length && _x < ST7920_WIDTH; i += 2, _x += 2)
        {
            ST7290_SetPixel(_x, y, false);
        }
    }
}

void ST7920_DrawLineBresenham(int x0, int y0, int x1, int y1)
{
    int dx = abs(x1 - x0);
    int sx = x0 < x1 ? 1 : -1;
    int dy = -abs(y1 - y0);
    int sy = y0 < y1 ? 1 : -1;

    int err = dx + dy, e2; /* error value e_xy */

    for (;;)
    {
        ST7290_SetPixel(x0, y0, 1);

        if (x0 == x1 && y0 == y1) break;
        e2 = 2 * err;
        if (e2 >= dy)
        {
            err += dy;
            x0 += sx;
        }

        if (e2 <= dx)
        {
            err += dx;
            y0 += sy;
        }
    }
}

void ST7920_DrawLineVerticalEx(u8 x, u8 y, u8 length, bool dotted)
{
    // ensure the line doesn't go off-screen
    u8 newLen = length;
    if (y + newLen > 64)
    {
        newLen -= y;
    }

    u8 shift = x & 7;
    u8 xIdx  = x / 8;

    if (!dotted)
    {
        for (int i = 0; i < newLen; y++, i++)
        {
            ST7920_BackBuf[(y * 16 + xIdx)] |= 0x80 >> shift;
        }
    }
    else
    {
        for (int i = 0, _x = x + ST7920_DottedDefaultState; i < newLen; y++, i++, _x++)
        {
            ST7920_BackBuf[(y * 16 + xIdx)] |= (0x80 >> shift) * (_x & 1);
        }
    }
}

void ST7920_DrawRectangleOutlineEx(u8 x, u8 y, u8 width, u8 height, u8 thickness, bool cutCorners, bool dotted)
{
    int hLen = width - cutCorners * 2;
    int vLen = height - 2 * thickness;

    int hStart = x + cutCorners;
    int vStart = y + thickness;

    if (dotted)
    {
        for (int i = 0; i < thickness; ++i)
        {
            ST7920_DrawLineHorizontal(hStart, y + i, hLen);
            ST7920_DrawLineHorizontal(hStart, y + height - i - 1, hLen);

            int leftSideX  = x + i;
            int rightSideX = x + width - i - 1;

            ST7920_DrawLineVertical(leftSideX, vStart, vLen);
            ST7920_DrawLineVertical(rightSideX, vStart, vLen);

            int offset = -ST7920_DottedOffset;
            int k      = offset;
            int mod    = 4;

            for (int j = vStart; j != vStart + vLen; j++, k++)
            {
                if (k % mod == 0)
                {
                    ST7290_SetPixel(leftSideX, j, false);
                }
            }

            for (int j = hStart; j != hStart + hLen; j++, k++)
            {
                if (k % mod == 0)
                {
                    ST7290_SetPixel(j, vStart + vLen, false);
                }
            }

            for (int j = vStart + vLen - 1; j != vStart - 1; j--, k++)
            {
                if (k % mod == 0)
                {
                    ST7290_SetPixel(rightSideX, j, false);
                }
            }

            for (int j = hStart + hLen - 1; j != hStart - 1; j--, k++)
            {
                if (k % mod == 0)
                {
                    ST7290_SetPixel(j, vStart - 1, false);
                }
            }
        }
    }
    else
    {
        for (int i = 0; i < thickness; ++i)
        {
            ST7920_DrawLineHorizontal(hStart, y + i, hLen);
            ST7920_DrawLineHorizontal(hStart, y + height - i - 1, hLen);

            ST7920_DrawLineVertical(x + i, vStart, vLen);
            ST7920_DrawLineVertical(x + width - i - 1, vStart, vLen);
        }
    }
}

