void ST7290_SetPixel(int x, int y, bool p)
{
    int addr             = y * 16 + x / 8;
    int sub              = 7 - (x & 7);
    ST7920_BackBuf[addr] = (ST7920_BackBuf[addr] & ~(1 << sub)) | (p << sub);
}

void ST7920_DrawCircleOutline(int cx, int cy, int r)
{
    int x = 0, y = r;
    int d = 3 - 2 * r;

    while (y >= x)
    {
        ST7290_SetPixel(cx + x, cy + y, 1);
        ST7290_SetPixel(cx - x, cy + y, 1);
        ST7290_SetPixel(cx + x, cy - y, 1);
        ST7290_SetPixel(cx - x, cy - y, 1);
        ST7290_SetPixel(cx + y, cy + x, 1);
        ST7290_SetPixel(cx - y, cy + x, 1);
        ST7290_SetPixel(cx + y, cy - x, 1);
        ST7290_SetPixel(cx - y, cy - x, 1);

        if (d <= 0)
        {
            d = d + 4 * x + 6;
        }
        else
        {
            d = d + 4 * (x - y) + 10;
            y--;
        }
        x++;
    }
}

